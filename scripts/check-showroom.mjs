import assert from 'node:assert/strict';
import { readFileSync, existsSync } from 'node:fs';
import sharp from 'sharp';
const html = readFileSync('.next/server/app/index.html', 'utf8');
assert.doesNotMatch(html, /class="[^"]*\bundefined\b/);
assert.equal((html.match(/<h1\b/g) || []).length, 1);
for (const id of ['home', 'transformation', 'products', 'room-explorer', 'gallery', 'why-us', 'contact']) assert.ok(html.includes(`id="${id}"`), `Missing ${id} section`);
for (const match of html.matchAll(/href="#([^"]+)"/g)) assert.ok(html.includes(`id="${match[1]}"`), `Broken anchor ${match[1]}`);
assert.match(html, /tel:\+916377223181/); assert.match(html, /tel:\+917073290182/);
assert.match(html, /mailto:parthsevak97@gmail.com/); assert.match(html, /wa\.me\/916377223181/);
assert.match(html, /23\.952773/); assert.match(html, /74\.083259/);
assert.doesNotMatch(html, /98XXX|9800000000|City Name|Shop No\. XX|Trusted by hundreds|free of charge|computerized tinting/i);
assert.doesNotMatch(html, /Where to paint|Search by name or code|Find Your Perfect Shade/);
const schema = JSON.parse(html.match(/<script type="application\/ld\+json">([^<]+)<\/script>/)[1]);
assert.equal(schema.telephone, '+916377223181'); assert.equal(schema.openingHours, 'Mo-Su 08:00-20:00');
assert.equal(schema.address.addressRegion, 'Rajasthan');
for (const file of ['neutral-room.webp', 'transformed-room.webp', 'soft-neutral.webp', 'deep-burgundy.webp', 'exterior.webp', 'preparation.webp']) assert.ok(existsSync(`public/images/showroom/${file}`));
const a = await sharp('public/images/showroom/neutral-room.webp').metadata();
const b = await sharp('public/images/showroom/transformed-room.webp').metadata();
assert.equal(a.width, b.width); assert.equal(a.height, b.height);
assert.ok(!readFileSync('package.json', 'utf8').includes('"motion"'));
assert.match(readFileSync('src/components/sections/Transformation.tsx', 'utf8'), /pin: desktop \? stage.current : false/);
assert.match(readFileSync('src/components/layout/Navbar.tsx', 'utf8'), /inert=\{!open\}/);
console.log('Showroom checks passed: sections, anchors, contact URLs, verified schema, no obsolete studio/fake data, registered assets and responsive motion guards.');
// The final invitation keeps both conversion actions and business details in HTML.
const ending = html.match(/<section\b[^>]*id="contact"[\s\S]*?<\/section>/)?.[0];
assert.ok(ending);
assert.equal((ending.match(/data-closing-line=/g) || []).length, 3);
assert.match(ending, /wa\.me\/916377223181/);
assert.match(ending, /destination=23\.952773/);
assert.match(ending, /closing-interior.webp/);
assert.match(ending, /not our shop interior/);
const footer = html.match(/<footer\b[\s\S]*?<\/footer>/)?.[0];
assert.ok(footer && footer.includes('parthsevak97@gmail.com'));
assert.match(footer, /8 AM/);
assert.doesNotMatch(footer, /data-closing-wordmark|data-footer-wordmark/);
assert.ok(existsSync('public/images/showroom/closing-interior.webp'));
console.log('Closing-section checks passed: three masked lines, both verified CTAs, labelled photograph and practical footer.');
